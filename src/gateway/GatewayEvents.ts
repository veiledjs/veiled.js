export type GatewayEventName = keyof typeof GatewayEvents;

const GATEWAY_EVENT_NAMES = new Set<string>(Object.values(GatewayEvents));

export function isGatewayEventName(value: string): value is GatewayEventName {
    return GATEWAY_EVENT_NAMES.has(value);
}
